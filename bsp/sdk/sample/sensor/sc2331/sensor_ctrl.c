static void SENSOR_configInitSeq(uint8_t path_idx)
{
	int fd = g_i2c_fd[0];
	int slave_addr = k_i2c_slave_addr[path_idx];
	int set_30fps = 0;
	int set_pseudo_master_15fps = 0;
	int set_pseudo_slave_15fps = 0;
	int set_pseudo_master_20fps = 0;
	int set_pseudo_slave_20fps = 0;

#ifdef SET_1920_1080_30fps_2lane
	set_30fps = 1;
#endif
#ifdef SET_1920_1080_15fps_2lane_PSEUDO_MASTER
	set_pseudo_master_15fps = 1;
#endif
#ifdef SET_1920_1080_15fps_2lane_PSEUDO_SLAVE
	set_pseudo_slave_15fps = 1;
#endif
#ifdef SET_1920_1080_20fps_2lane_PSEUDO_MASTER
	set_pseudo_master_20fps = 1;
#endif
#ifdef SET_1920_1080_20fps_2lane_PSEUDO_SLAVE
	set_pseudo_slave_20fps = 1;
#endif

	if (set_30fps) {
		SENSOR_writeSeqWaddrBdata(fd, sizeof(k_cmd_format_1080p_30fps) / sizeof(SensCmd),
		                          k_cmd_format_1080p_30fps, slave_addr);
	} else if (set_pseudo_master_15fps) {
		SENSOR_writeSeqWaddrBdata(fd, sizeof(k_cmd_format_1080p_pseudo_master_15fps) / sizeof(SensCmd),
		                          k_cmd_format_1080p_pseudo_master_15fps, slave_addr);
	} else if (set_pseudo_slave_15fps) {
		SENSOR_writeSeqWaddrBdata(fd, sizeof(k_cmd_format_1080p_pseudo_slave_15fps) / sizeof(SensCmd),
		                          k_cmd_format_1080p_pseudo_slave_15fps, slave_addr);
	} else if (set_pseudo_master_20fps) {
		SENSOR_writeSeqWaddrBdata(fd, sizeof(k_cmd_format_1080p_pseudo_master_20fps) / sizeof(SensCmd),
		                          k_cmd_format_1080p_pseudo_master_20fps, slave_addr);
		SENSOR_writeSeqWaddrBdata(fd, sizeof(k_cmd_format_1080p_20fps) / sizeof(SensCmd),
		                          k_cmd_format_1080p_20fps, slave_addr);
	} else if (set_pseudo_slave_20fps) {
		SENSOR_writeSeqWaddrBdata(fd, sizeof(k_cmd_format_1080p_pseudo_slave_20fps) / sizeof(SensCmd),
		                          k_cmd_format_1080p_pseudo_slave_20fps, slave_addr);
		SENSOR_writeSeqWaddrBdata(fd, sizeof(k_cmd_format_1080p_20fps) / sizeof(SensCmd),
		                          k_cmd_format_1080p_20fps, slave_addr);
	} else {
		// No valid setting was chosen
		fprintf(stderr, "Error: (%s) no sensor setting was applied.\n", __func__);
		return;
	}

	// TODO: verify if update_exp_cmd is required
#ifdef SNS0
	cmos_ctrl(SNS0_ID).update_exp_cmd(fd, path_idx);
#endif
#ifdef SNS1
	cmos_ctrl(SNS1_ID).update_exp_cmd(fd, path_idx);
#endif
#ifdef SNS2
	cmos_ctrl(SNS2_ID).update_exp_cmd(fd, path_idx);
#endif

	SENSOR_writeSeqWaddrBdata(fd, sizeof(k_cmd_start) / sizeof(SensCmd), k_cmd_start, slave_addr);
}

static void SENSOR_configExitSeq(uint8_t path_idx)
{
	int fd = g_i2c_fd[0];
	int slave_addr = k_i2c_slave_addr[path_idx];

	SENSOR_writeSeqWaddrBdata(fd, sizeof(k_cmd_stop) / sizeof(SensCmd), k_cmd_stop, slave_addr);
}

/* Global Interface */
void SENSOR_configInit(uint8_t path_idx)
{
	int ret = 0;
	int i2c_fd = -1;

	if (path_idx >= SENSOR_PATH_MAX) {
		fprintf(stderr, "Error: (%s) Unsupported sensor index %d.\n", __func__, path_idx);
		return;
	}

	/* Open I2C device node */
	ret = SENSOR_openI2cDev(&i2c_fd, k_i2c_slave_addr[path_idx]);
	if (ret != MPI_SUCCESS) {
		return;
	}

	g_i2c_fd[0] = i2c_fd;

	/* Start sensor */
	SENSOR_configInitSeq(path_idx);
}

void SENSOR_configExit(uint8_t path_idx)
{
	int ret = 0;
	int i2c_fd = g_i2c_fd[0];

	if (path_idx >= SENSOR_PATH_MAX) {
		fprintf(stderr, "Error: (%s) Unsupported sensor index %d.\n", __func__, path_idx);
		return;
	}

	/* Stop sensor */
	SENSOR_configExitSeq(path_idx);

	if (g_i2c_fd[0] != -1) {
		/* Close I2C device node */
		ret = SENSOR_closeI2cDev(i2c_fd);
		if (ret != MPI_SUCCESS) {
			return;
		}

		g_i2c_fd[0] = -1;
	}
}

int32_t SENSOR_getOpInfo(uint8_t path_idx, uint32_t sns_idx, MPI_SNS_OP_INFO_S *p_op_info)
{
	MPI_SNS_OP_INFO_S *p = p_op_info;
	float sensor_fps = SENSOR_FPS;
	int16_t frame_len_line = SENSOR_HEIGHT;
	int i;

	p->sensor_mode = MPI_SNS_MODE_MASTER;
	p->slv_sync_src = MPI_SLV_SYNC_SRC_NONE;
	p->bit_width = MPI_BITS_10;
	p->intf_ptcl = MPI_INTF_PTCL_MIPI;
	p->ptcl_mode = MPI_MIPI_CSI2;
	p->hsync_plty = MPI_PLTY_HIGH;
	p->vsync_plty = MPI_PLTY_HIGH;
	p->bayer = MPI_BAYER_PHASE_B; // Sensor Datasheet spec 2.1.1 n [0,0]= Blue
	p->ext_clk_freq = SENSOR_EXT_CLK_FREQ;
	p->sensor_res.width = SENSOR_WIDTH;
	p->sensor_res.height = SENSOR_HEIGHT;
	p->sensor_fps = sensor_fps;
	p->frame_len_line = frame_len_line;
	p->i2c_slv_addr = k_i2c_slave_addr[path_idx];
	p->ob_enable = 0;
	p->reserved = 0;

	p->parl_lane = k_parl_lane[0];
	for (i = 0; i < MPI_MAX_LVDSRX_LANE_NUM; i++) {
		p->serl_lane[i] = k_serl_lane[0][i];
	}

	p->mipi.bp_img.hor = 0;
	p->mipi.bp_img.ver = 0;
	p->mipi.fp_img.hor = 0;
	p->mipi.fp_img.ver = 0;

	p->mipi.ob_conf.skipped_line_num = 0;
	p->mipi.ob_conf.pos = MPI_POS_NONE;
	p->mipi.ob_conf.region.x = 0;
	p->mipi.ob_conf.region.y = 0;
	p->mipi.ob_conf.region.width = 0;
	p->mipi.ob_conf.region.height = 0;

	p->mipi.vc_bmp = 0x1;
	p->mipi.dt_bmp = 0x0;
	p->mipi.t_hs_settle = 0xA;
	p->mipi.t_hs_settle_ns = T_HS_SETTLE_NS;
	p->mipi.t_d_term_en_ns = T_D_TERM_EN_NS;
	p->mipi.t_clk_settle_ns = T_CLK_SETTLE_NS;
	p->mipi.t_clk_term_en_ns = T_CLK_TERM_EN_NS;

	return MPI_SUCCESS;
}
