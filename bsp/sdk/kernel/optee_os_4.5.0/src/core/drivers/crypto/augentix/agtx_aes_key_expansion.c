#define BITS_PER_BYTE 8
#define BYTES_PER_WORD 4
#define ONE_BYTE_BITS (1 * BITS_PER_BYTE)
#define THREE_BYTE_BITS (3 * BITS_PER_BYTE)

/* Word Masks */
#define MSK_BYTE0 0x000000FFU
#define MSK_BYTE1 0x0000FF00U
#define MSK_BYTE2 0x00FF0000U
#define MSK_BYTE3 0xFF000000U

/* AES Maximum Limits (Based on AES-256) */
#define AES_MAX_NK 8
#define AES_MAX_NR 14
#define AES_MAX_NB 4
#define AES_SCHEDULE_WORDS (AES_MAX_NB * (AES_MAX_NR + 1))

/* AES Configuration Structure */
typedef struct {
	int nk;
	int nb;
	int nr;
} aes_config_t;

static const aes_config_t g_agtx_aes_cfg[] = { [AES_CIPHER_128] = { .nk = 4, .nb = 4, .nr = 10 },
	                                       [AES_CIPHER_256] = { .nk = 8, .nb = 4, .nr = 14 } };

