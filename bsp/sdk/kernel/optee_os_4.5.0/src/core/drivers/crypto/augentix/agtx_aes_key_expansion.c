/**
 * aes_sub_word: Applies the S-box to each of the four bytes in a word.
 */
uint32_t aes_sub_word(uint32_t word)
{
	uint32_t tmp = 0;
	for (int i = 0; i < BYTES_PER_WORD; i++) {
		uint8_t shift_bits = i * BITS_PER_BYTE;
		uint8_t substituted = g_agtx_aes_sbox[(uint8_t)((word >> shift_bits) & MSK_BYTE0)];
		tmp |= ((uint32_t)substituted << shift_bits);
	}
	return tmp;
}

/**
 * aes_rot_word: [a0,a1,a2,a3] -> [a1,a2,a3,a0].
 */
uint32_t aes_rot_word(uint32_t word)
{
	return (word >> ONE_BYTE_BITS) | ((word & MSK_BYTE0) << THREE_BYTE_BITS);
}

/**
 * aes_swap_word: Byte swap.
 */
uint32_t aes_swap_word(uint32_t word)
{
	return (((word & MSK_BYTE0) << THREE_BYTE_BITS) | ((word & MSK_BYTE1) << ONE_BYTE_BITS) |
	        ((word & MSK_BYTE2) >> ONE_BYTE_BITS) | ((word & MSK_BYTE3) >> THREE_BYTE_BITS));
}

/**
 * aes_key_expansion: Derives the Round Key schedule from the Cipher Key.
 */
void aes_key_expansion(AES_CIPHER_T mode, uint32_t *key, uint32_t *result)
{
	const int nk = g_agtx_aes_cfg[mode].nk;
	const int nb = g_agtx_aes_cfg[mode].nb;
	const int nr = g_agtx_aes_cfg[mode].nr;
	const int total_words = nb * (nr + 1);

	uint32_t w[AES_SCHEDULE_WORDS] = { 0 };
	int i;

	DMSG("Initialize nk");
	for (i = 0; i < nk; i++) {
		w[i] = key[i];
	}

	DMSG("Generate aes sub word");
	for (i = nk; i < total_words; i++) {
		uint32_t temp = w[i - 1];

		if ((i % nk) == 0) {
			temp = aes_sub_word(aes_rot_word(temp)) ^ aes_swap_word(g_agtx_aes_rcon[i / nk - 1]);
		} else if (nk > 6 && (i % nk) == 4) {
			temp = aes_sub_word(temp);
		}

		w[i] = w[i - nk] ^ temp;
	}

	DMSG("Calculate key expansion result");
	for (int j = nk, idx = total_words - 1; j > 0; j--, idx--) {
		result[j - 1] = w[idx];
	}
}
