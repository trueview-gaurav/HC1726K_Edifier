static void convert_pca_table_data(uint8_t init_h, uint8_t init_s, uint8_t init_l,
                                   const int16_t hue[][PCA_CTRL_POINTS_NUM_S][PCA_CTRL_POINTS_NUM_H],
                                   const int16_t sat[][PCA_CTRL_POINTS_NUM_S][PCA_CTRL_POINTS_NUM_H],
                                   const int16_t lightness[][PCA_CTRL_POINTS_NUM_S][PCA_CTRL_POINTS_NUM_H],
                                   int32_t word_length, int32_t *wdata)
{
	uint8_t idx_h = init_h;
	uint8_t idx_s = init_s;
	uint8_t idx_l = init_l;
	int32_t k;
	for (k = 0; k < word_length; k++) {
		wdata[k] = hue[idx_l][idx_s][idx_h] << 16 | sat[idx_l][idx_s][idx_h] << 8 |
		           lightness[idx_l][idx_s][idx_h];
		idx_h = idx_h + 2;
		if (idx_h >= PCA_CTRL_POINTS_NUM_H) {
			idx_h = init_h;
			idx_s = idx_s + 2;
			if (idx_s >= PCA_CTRL_POINTS_NUM_S) {
				idx_s = init_s;
				idx_l = idx_l + 2;
			}
		}
	}
}

static void convert_table_to_cfg(const int16_t hue[][PCA_CTRL_POINTS_NUM_S][PCA_CTRL_POINTS_NUM_H],
                                 const int16_t sat[][PCA_CTRL_POINTS_NUM_S][PCA_CTRL_POINTS_NUM_H],
                                 const int16_t lightness[][PCA_CTRL_POINTS_NUM_S][PCA_CTRL_POINTS_NUM_H],
                                 struct pca_table_cfg *cfg)
{
	convert_pca_table_data(0, 0, 0, hue, sat, lightness, PCA_EEE_WORD_NUM, &cfg->eee[0]);
	convert_pca_table_data(0, 1, 0, hue, sat, lightness, PCA_EOE_WORD_NUM, &cfg->eoe[0]);
	convert_pca_table_data(1, 0, 0, hue, sat, lightness, PCA_OEE_WORD_NUM, &cfg->oee[0]);
	convert_pca_table_data(1, 1, 0, hue, sat, lightness, PCA_OOE_WORD_NUM, &cfg->ooe[0]);
	convert_pca_table_data(0, 0, 1, hue, sat, lightness, PCA_EEO_WORD_NUM, &cfg->eeo[0]);
	convert_pca_table_data(0, 1, 1, hue, sat, lightness, PCA_EOO_WORD_NUM, &cfg->eoo[0]);
	convert_pca_table_data(1, 0, 1, hue, sat, lightness, PCA_OEO_WORD_NUM, &cfg->oeo[0]);
	convert_pca_table_data(1, 1, 1, hue, sat, lightness, PCA_OOO_WORD_NUM, &cfg->ooo[0]);
}

inline void isp_calc_pca_reg(struct isp_frame_table *ftbl)
{
	convert_table_to_cfg(k_pca_default_hue, k_pca_default_sat, k_pca_default_lightness, &ftbl->pca_table);
}

void isp_pca_set_table_cfg(volatile CsrBankPca *csr, const struct pca_table_cfg *cfg)
{
	int i = 0;
	csr->table_en = 1;
	csr->table_eee_w_addr = 0;
	for (i = 0; i < PCA_EEE_WORD_NUM; i++) {
		csr->table_eee_w_data = cfg->eee[i];
	}
	csr->table_eoe_w_addr = 0;
	for (i = 0; i < PCA_EOE_WORD_NUM; i++) {
		csr->table_eoe_w_data = cfg->eoe[i];
	}
	csr->table_oee_w_addr = 0;
	for (i = 0; i < PCA_OEE_WORD_NUM; i++) {
		csr->table_oee_w_data = cfg->oee[i];
	}
	csr->table_ooe_w_addr = 0;
	for (i = 0; i < PCA_OOE_WORD_NUM; i++) {
		csr->table_ooe_w_data = cfg->ooe[i];
	}
	csr->table_eeo_w_addr = 0;
	for (i = 0; i < PCA_EEO_WORD_NUM; i++) {
		csr->table_eeo_w_data = cfg->eeo[i];
	}
	csr->table_eoo_w_addr = 0;
	for (i = 0; i < PCA_EOO_WORD_NUM; i++) {
		csr->table_eoo_w_data = cfg->eoo[i];
	}
	csr->table_oeo_w_addr = 0;
	for (i = 0; i < PCA_OEO_WORD_NUM; i++) {
		csr->table_oeo_w_data = cfg->oeo[i];
	}
	csr->table_ooo_w_addr = 0;
	for (i = 0; i < PCA_OOO_WORD_NUM; i++) {
		csr->table_ooo_w_data = cfg->ooo[i];
	}
	csr->table_en = 0;
}